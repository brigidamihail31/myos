"""Ядро учебной операционной системы.

Модуль kernel.py:
  * НЕ работает с базой данных напрямую (кроме save/load состояния памяти);
  * НЕ выполняет файловые операции;
  * хранит состояние системы и распределяет ресурсы.

Три задачи ядра:
  1. Хранить состояние: текущий пользователь, счётчик PID,
     объём используемой памяти, лимит памяти.
  2. Распределять ресурсы: выдавать PID, выделять/освобождать память,
     проверять лимит.
  3. Быть точкой сбора информации о состоянии системы (memory_info).

Дополнительно: состояние памяти сохраняется в БД (таблица memory_state),
чтобы не терялось при перезапуске ОС.
"""
from . import db


class Kernel:
    """Монолитное ядро учебной ОС."""

    # -----------------------------------------------------------------
    # Инициализация
    # -----------------------------------------------------------------
    def __init__(self):
        self.current_user = "guest"   # текущий пользователь сессии
        self.process_counter = 0      # счётчик выданных PID
        self.memory_used = 0          # использованная память (МБ)
        self.memory_limit = 1024      # лимит памяти (МБ)

    # -----------------------------------------------------------------
    # Задача 1. Хранение состояния
    # -----------------------------------------------------------------
    def set_user(self, login: str) -> None:
        """Установить текущего пользователя (после успешного sys_login)."""
        self.current_user = login

    def get_user(self) -> str:
        """Вернуть имя текущего пользователя."""
        return self.current_user

    # -----------------------------------------------------------------
    # Задача 2. Распределение ресурсов
    # -----------------------------------------------------------------
    def allocate_pid(self) -> int:
        """Выдать новый идентификатор процесса (PID)."""
        self.process_counter += 1
        return self.process_counter

    def allocate_memory(self, size: int) -> bool:
        """Выделить память.

        Возвращает True при успехе и False, если запрошенный объём
        превысил бы лимит. Состояние сохраняется в БД.
        """
        if self.memory_used + size > self.memory_limit:
            return False
        self.memory_used += size
        self.save_memory_state()
        return True

    def free_memory(self, size: int) -> None:
        """Освободить память (не уходя в отрицательные значения).

        Состояние сохраняется в БД.
        """
        self.memory_used = max(0, self.memory_used - size)
        self.save_memory_state()

    # -----------------------------------------------------------------
    # Задача 3. Сбор информации о состоянии
    # -----------------------------------------------------------------
    def memory_info(self) -> dict:
        """Сводка по памяти: used / limit / free (в МБ)."""
        return {
            "used": self.memory_used,
            "limit": self.memory_limit,
            "free": self.memory_limit - self.memory_used,
        }

    # -----------------------------------------------------------------
    # Синхронизация состояния памяти с БД
    # -----------------------------------------------------------------
    def save_memory_state(self) -> None:
        """Сохранить состояние памяти в таблицу memory_state.

        Удаляем старую запись и вставляем новую (таблица всегда
        содержит ровно одну строку — текущее состояние).
        """
        db.execute_delete("memory_state", {})
        db.execute_insert("memory_state", {
            "used": self.memory_used,
            "limit_": self.memory_limit,
        })

    def load_memory_state(self) -> None:
        """Загрузить состояние памяти из БД (если запись есть)."""
        states = db.execute_select("memory_state")
        if states:
            self.memory_used = states[0]["used"]
            self.memory_limit = states[0]["limit_"]

    # -----------------------------------------------------------------
    # Служебные методы
    # -----------------------------------------------------------------
    def boot(self) -> None:
        """Загрузить ядро: инициализировать схему БД и восстановить
        состояние памяти из прошлого запуска."""
        db.init_db()
        self.load_memory_state()
        print("[kernel] Ядро загружено, состояние памяти восстановлено.")

    def reset(self) -> None:
        """Полный сброс: пользователь — guest, память освобождена."""
        self.current_user = "guest"
        self.memory_used = 0
        self.save_memory_state()


# Глобальный экземпляр ядра — создаётся один раз при запуске ОС
# и используется всеми остальными модулями (syscalls.py, shell.py).
kernel_instance = Kernel()